    // --------------------------------- Task 1 ----------------------------------
    int arr1[5] = {1,2,9,4,5};
    // ============================================================================

    // --------------------------------- Task 2 -----------------------------------
    int sum = 0;

    // Старий формат циклу for до стандарту c11, краще не використовувати для MISRA
    for (int i = 0; i < 5; i++) {
        sum += arr1[i];
    }
    // ============================================================================

    // --------------------------------- Task 3 -----------------------------------
    int max_num = 0;
    for (const int it : arr1) {
        if (it > max_num) {
            max_num = it;
        }
    }

    cout << "\nСума всіх елементів масиву: " << sum << "\nМаксимальний елемент: " << max_num << endl;
    // ============================================================================


    // ------------------------Задача: "Унікальний елемент" -----------------------
    // --------------------------Task 4. "Unique element" -------------------------
    cout << "-------------------------- Task 4 --------------------------" << endl;
    // У тебе є масив із 9 цілих чисел. Відомо, що коже число в ньому повторюється рівно двічі,
    // і лише одне число є унікальним (зустрічається тільки один раз).
    // Приклад масиву:
    // int arr[9] = {4, 1, 2, 1, 2, 8, 4, 9, 8};
    int arr2[9] = {4, 1, 2, 1, 2, 8, 4, 8, 18};
    int unique_num = 0;

    for (int i = 0; i < 9; i++) {
        int count = 0;

        for (int j = 0; j < 9; j++) {
            if (arr2[i] == arr2[j]) {
                count++;
            }
        }
        if (count == 1) {
            unique_num = arr2[i];
        }
    }
    cout << "Unique element: " << unique_num << endl;

    // Скорочений запис: unique_num = unique_num ^ val
    //     Властивості XOR:
    // A⊕A=0 (будь-яке число XOR само із собою дає 0).
    // A⊕0=A (число XOR 0 залишає число без змін).
    for (int val : arr2) {
        unique_num ^= val;
    }

    //     Що треба зробити:
