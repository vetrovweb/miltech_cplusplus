    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            cout << matrix[i][j] << " ";
        }
        cout << endl;
    }

    int result[3][2] = {};

    for (int i = 0; i < 2; i++) {
        for (int j = 0; j < 3; j++) {
            result[j][i] = matrix[i][j];
        }
    }

    for (const auto& row : result) {                            // row — це посилання на рядок (масив із 2 елементів)
        for (int val : row) {                                               // val — це конкретне число з цього рядка
            std::cout << val << " ";
        }
        std::cout << "\n";
    }

    return 0;
